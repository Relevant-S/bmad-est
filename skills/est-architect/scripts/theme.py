"""The diagram's design tokens, in one place, derived from the company palette.

Sections E, F and G of the design contract are a complete visual system — colours, radii, the
type scale, the icon rules. The previous diagram had none of it: group titles were the same size
and weight as node labels, and the only colours were whatever the renderer defaulted to.

Two rules shaped this file.

**No hex is written twice.** `est-estimate/assets/brand.json` is already the source for the HTML
reports, the calibration report and the workbook. The diagram reads the same file, so the
deliverables stay one visual identity instead of drifting apart the way three hardcoded palettes
did before `brand.py` existed.

**Prefer an authored prop to a stylesheet.** Fill, border, radius, title chip, font size and
label colour are all real props on the renderer's own schema, so they are authored per entity and
survive a renderer upgrade. CSS is used only where the renderer hardcodes a value with no prop
behind it — title weight, letter-spacing and case, the shadow, and the icon caption. Those rules
carry `!important` because per-template CSS is injected after `baseCss` inside an `@scope` block
and would otherwise win; each one says which stock rule it is fighting.

    uv run scripts/theme.py            # the token table
    uv run scripts/theme.py --render   # what render.mjs loads
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRAND = HERE.parent.parent / "est-estimate" / "assets" / "brand.json"

# E2's neutral alternative rather than the cream: the brand is navy, and a cream boundary around
# a navy system reads as two identities in one picture.
ZONE_FILL, ZONE_BORDER = "#F8F9FB", "#CBD2DC"
GROUP_FILL = "#F7FAFE"
CHIP_FILL = "#FFFFFF"
EDGE_INK = "#4B5563"
GLYPH_INK = "#374151"          # F1: one outline set, one ink, never a coloured shape

# G. One scale, so a title cannot be mistaken for a label.
TYPE = {
    "zone_title": {"px": 12, "weight": 600, "tracking": "0.05em", "upper": True},
    "group_title": {"px": 11, "weight": 600, "tracking": "0.04em", "upper": True},
    "node_name": {"px": 12.5, "weight": 500},
    "node_role": {"px": 11, "weight": 400},
    "edge_label": {"px": 10.5, "weight": 400},
}

# C. The 8px grid.
CELL_W = 120
ICON_PX = 40
ICON_GAP = 8
NAME_LINE = 16
ROLE_LINE = 14
# 40 icon + 8 gap + two 16px name lines + one 14px role line = 94, on the 8px grid = 96.
CELL_H = 96
GAP_X, GAP_Y = 24, 16
GROUP_PAD = "[top=48,left=20,bottom=20,right=20]"
ZONE_PAD = "[top=52,left=24,bottom=24,right=24]"

# The renderer multiplies an authored `lineWidth` by 1.75 to get its rendered stroke
# (`normalizers.js`: `lineWidth * 1.75`), so D8's 1.25px is authored as 1.25/1.75.
STROKE_PX = 1.25
LINE_WIDTH = round(STROKE_PX / 1.75, 4)


def brand(path=None):
    try:
        return json.loads(Path(path or BRAND).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        # A diagram in the wrong blue is worth shipping; one that does not render is not.
        return {"palette": {"light": {"brand": "#2563EB", "ink": "#1F2937",
                                      "muted": "#6B7280", "line": "#E0E0E0"}},
                "font": {"css_family": "Arial, Helvetica, sans-serif"}}


def tokens(data=None):
    data = data or brand()
    light = (data.get("palette") or {}).get("light") or {}
    accent = light.get("brand", "#2563EB")
    return {
        "canvas": "#FFFFFF",
        "zone_fill": ZONE_FILL, "zone_border": ZONE_BORDER,
        "group_fill": GROUP_FILL, "group_border": accent,
        "chip_fill": CHIP_FILL,
        "ink": light.get("ink", "#1F2937"),
        "muted": light.get("muted", "#6B7280"),
        "edge": EDGE_INK,
        "accent": accent,
        "glyph": GLYPH_INK,
        "font": (data.get("font") or {}).get("css_family", "Arial, Helvetica, sans-serif"),
        "family": (data.get("font") or {}).get("local_first", "Arial"),
        "fallback": (data.get("font") or {}).get("fallback", "Arial"),
        "radius": 8,
        "stroke": STROKE_PX,
        "line_width": LINE_WIDTH,
        "type": TYPE,
        "cell": {"width": CELL_W, "height": CELL_H, "icon": ICON_PX, "gap": ICON_GAP,
                 "gap_x": GAP_X, "gap_y": GAP_Y},
        "padding": {"group": GROUP_PAD, "zone": ZONE_PAD},
    }


def base_css(t=None):
    """What no prop can reach.

    Every rule below replaces a value the renderer hardcodes. `!important` is not decoration:
    per-template CSS is injected AFTER `baseCss` inside an `@scope` block, so an equal-specificity
    rule of ours loses. The attribute selector is the template's own mount host.
    """
    t = t or tokens()
    ty = t["type"]
    return f"""
/* est-architect theme. Generated by scripts/theme.py from est-estimate/assets/brand.json. */
:root {{ --er-ground: {t['canvas']}; }}

/* G2/G3. Stock Group CSS hardcodes `font-weight:400; letter-spacing:-0.01em` on the title and
   has no text-transform at all, so a group title reads at the same weight as a node label. */
[data-mdp-tag="Group"] .er-grouplike__title {{
  font-weight: {ty['group_title']['weight']} !important;
  letter-spacing: {ty['group_title']['tracking']} !important;
  text-transform: uppercase !important;
}}

/* E7. Stock is `box-shadow:4px 4px 0 0 #e8e8e8` — a hard offset block, not a lift. */
[data-mdp-tag="Group"] .er-grouplike[data-style='shadow'] {{
  box-shadow: 0 1px 3px rgba(16, 24, 40, 0.08) !important;
}}

/* F3 + G4/G5 + defect 8. Stock pins the caption to `position:absolute; width:max-content;
   max-width:180%` of the figure, and the figure is the glyph when no bounds are authored — which
   is why a label wrapped at ~90px. Worse, stock switches to `white-space:nowrap` the moment
   there are two caption lines, so a name-and-role label would never wrap at all. */
/* C2/C8. One cell size for every node. The renderer measures an Icon's box from what it
   renders — an authored `width` becomes the GLYPH's size, not the box's — so the cell is a
   constant here. Without it a long name grew its own node and H9 saw seven different sizes. */
[data-mdp-tag="Icon"] .er-icon {{
  --er-glyph-num: {t['cell']['icon']} !important;
  width: {t['cell']['width']}px !important;
  /* Height is NOT pinned here: C8 wants one cell size for the diagram, and layout.py computes it
     from the longest name on this particular canvas. The figure fills the box it is given. */
  height: 100% !important;
}}
[data-mdp-tag="Icon"] .er-icon__glyph {{
  width: {t['cell']['icon']}px !important;
  height: {t['cell']['icon']}px !important;
}}
[data-mdp-tag="Icon"] figcaption.er-icon__caption {{
  position: static !important;
  transform: none !important;
  width: 100% !important;
  max-width: none !important;
  margin: {t['cell']['gap']}px 0 0 !important;
  /* G7: wrap at the cell width less the gutter, never at 1.8x the glyph. */
  max-width: {t['cell']['width'] - 8}px !important;
}}
[data-mdp-tag="Icon"] figcaption.er-icon__caption .er-icon__caption-line {{
  white-space: normal !important;
  overflow-wrap: break-word !important;
  line-height: 1.25 !important;
  letter-spacing: 0 !important;
}}
[data-mdp-tag="Icon"] .er-icon__caption-line:first-child {{
  font-weight: {ty['node_name']['weight']} !important;
}}
[data-mdp-tag="Icon"] .er-icon__caption-line + .er-icon__caption-line {{
  font-weight: {ty['node_role']['weight']} !important;
  margin-top: 2px !important;
}}
""".strip() + "\n"


def fonts(t=None):
    """G1. The brand face where the reader has it, Arial where they do not.

    PP Mori is licensed and cannot be embedded in a document handed to a client, which is the
    same decision `brand.json` records for the HTML reports. The consequence is that two machines
    can render different PNGs, so the render report carries `degradedFonts` and says which face
    was actually used rather than implying the output is machine-independent.
    """
    t = t or tokens()
    return {
        "roles": {"clean": t["family"], "rough": t["family"], "mono": "monospace"},
        "faces": [{"kind": "system", "family": t["family"]}],
        "fallbacks": {"clean": t["fallback"] + ", Helvetica, sans-serif",
                      "rough": t["fallback"] + ", Helvetica, sans-serif",
                      "mono": "ui-monospace, monospace"},
    }


def render_config(t=None):
    t = t or tokens()
    return {"baseCss": base_css(t), "fonts": fonts(t), "tokens": t}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", action="store_true", help="the object render.mjs loads")
    ap.add_argument("--css", action="store_true")
    ap.add_argument("-o", "--output")
    args = ap.parse_args()

    if args.css:
        text = base_css()
    elif args.render:
        text = json.dumps(render_config(), indent=2, ensure_ascii=False)
    else:
        text = json.dumps(tokens(), indent=2, ensure_ascii=False)
    if args.output:
        Path(args.output).write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
